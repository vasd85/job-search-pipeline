#!/usr/bin/env node

import {
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = resolve(repoRoot, "instructions/skills/manifest.json");
const runtimeContracts = {
  claude: {
    agent_root: ".claude/agents",
    root_file: "CLAUDE.md",
    runner_id: "claude-code",
    skill_root: ".claude/skills",
  },
  codex: {
    root_file: "AGENTS.md",
    runner_id: "codex",
    skill_root: ".agents/skills",
  },
};

function readManifest() {
  if (unsafeAncestors(manifestPath).length || pathType(manifestPath) !== "file") {
    throw new Error("Invalid repository-owned proxy manifest path");
  }
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  if (manifest.schema_version !== 1) throw new Error("Unsupported proxy manifest schema");
  if (!manifest.runtimes || !Array.isArray(manifest.skills) || !Array.isArray(manifest.agents)) {
    throw new Error("Invalid proxy manifest");
  }
  if (
    Object.keys(manifest.runtimes).sort().join("\n")
    !== Object.keys(runtimeContracts).sort().join("\n")
  ) {
    throw new Error("Invalid runtime proxy inventory");
  }
  for (const [runtimeName, expected] of Object.entries(runtimeContracts)) {
    const actual = manifest.runtimes[runtimeName];
    if (
      !actual
      || Object.entries(expected).some(([key, value]) => actual[key] !== value)
      || Object.keys(actual).sort().join("\n") !== Object.keys(expected).sort().join("\n")
    ) {
      throw new Error(`Invalid runtime proxy config for ${runtimeName}`);
    }
  }
  const names = new Set();
  for (const skill of manifest.skills) {
    if (!/^[a-z0-9-]+$/.test(skill.name)) throw new Error(`Invalid skill name: ${skill.name}`);
    if (names.has(skill.name)) throw new Error(`Duplicate skill name: ${skill.name}`);
    names.add(skill.name);
    if (!skill.description?.trim()) throw new Error(`Missing description for ${skill.name}`);
    const expectedCommon = `instructions/skills/${skill.name}.md`;
    const commonPath = resolve(repoRoot, expectedCommon);
    if (
      skill.common !== expectedCommon
      || unsafeAncestors(commonPath).length
      || pathType(commonPath) !== "file"
    ) {
      throw new Error(`Invalid canonical skill path for ${skill.name}`);
    }
    if (
      skill.claude?.["disable-model-invocation"] !== true
      || Object.keys(skill.claude ?? {}).join("\n") !== "disable-model-invocation"
    ) {
      throw new Error(`Invalid Claude invocation policy for ${skill.name}`);
    }
    if (
      skill.codex?.allow_implicit_invocation !== false
      || Object.keys(skill.codex ?? {}).join("\n") !== "allow_implicit_invocation"
    ) {
      throw new Error(`Invalid Codex invocation policy for ${skill.name}`);
    }
  }
  const agentNames = new Set();
  for (const agent of manifest.agents) {
    if (!/^[a-z0-9-]+$/.test(agent.name)) throw new Error(`Invalid agent name: ${agent.name}`);
    if (agentNames.has(agent.name)) throw new Error(`Duplicate agent name: ${agent.name}`);
    agentNames.add(agent.name);
    if (!agent.description?.trim()) throw new Error(`Missing description for ${agent.name}`);
    const commonPath = resolve(repoRoot, String(agent.common ?? ""));
    if (
      typeof agent.common !== "string"
      || !/^instructions\/agents\/[a-z0-9-]+\.md$/.test(agent.common)
      || unsafeAncestors(commonPath).length
      || pathType(commonPath) !== "file"
    ) {
      throw new Error(`Invalid canonical agent path for ${agent.name}`);
    }
    // The one tool a reader of untrusted text may have is reading. A manifest that hands an agent
    // anything else is refused here, before a file is written - the second layer under the pin.
    if (
      Object.keys(agent.claude ?? {}).sort().join("\n") !== "model\ntools"
      || !Array.isArray(agent.claude.tools)
      || agent.claude.tools.length !== 1
      || agent.claude.tools[0] !== "Read"
    ) {
      throw new Error(`Invalid agent tool allowlist for ${agent.name}`);
    }
    if (typeof agent.claude.model !== "string" || !/^[a-z0-9.-]+$/.test(agent.claude.model)) {
      throw new Error(`Invalid agent model for ${agent.name}`);
    }
  }
  return manifest;
}

function yamlValue(value) {
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  return JSON.stringify(value);
}

function rootProxy(runtimeName, runtime) {
  const label = runtimeName === "claude" ? "Claude Code" : "Codex";
  return `# ${runtime.root_file} — job-search-pipeline\n\n`
    + `> Generated by \`node tools/sync-agent-proxies.mjs --write\`. Do not add canonical rules here.\n\n`
    + `Runtime: **${label}**\n\n`
    + `\`runner_id\`: \`${runtime.runner_id}\`\n\n`
    + `Before taking any task action, read [instructions/operating-contract.md](instructions/operating-contract.md) `
    + `in full and follow it as the repository operating contract. Native skills in \`${runtime.skill_root}/\` `
    + `are generated discovery proxies; each one loads its canonical procedure from \`instructions/skills/\`.\n`;
}

function skillProxy(runtimeName, runtime, skill) {
  const overrides = runtimeName === "claude" ? skill.claude : {};
  const frontmatter = [
    "---",
    `name: ${skill.name}`,
    `description: ${yamlValue(skill.description)}`,
    ...Object.entries(overrides).map(([key, value]) => `${key}: ${yamlValue(value)}`),
    "---",
  ].join("\n");
  return `${frontmatter}\n\n# ${skill.name} — runtime proxy\n\n`
    + `Before taking any task action, read \`${skill.common}\` in full. Follow that file as the only `
    + `canonical procedure for this skill. Use \`runner_id\` from \`${runtime.root_file}\` whenever `
    + `the procedure records a process. Do not reconstruct or extend the procedure from this proxy.\n`;
}

/**
 * A Claude Code subagent: the frontmatter from the manifest and the canonical instruction verbatim.
 * The tools line is rendered as the plain literal the pin reads, not through `yamlValue`.
 */
function agentProxy(agent) {
  const canonical = readFileSync(resolve(repoRoot, agent.common), "utf8");
  return [
    "---",
    `name: ${agent.name}`,
    `description: ${yamlValue(agent.description)}`,
    `tools: ${agent.claude.tools.join(", ")}`,
    `model: ${agent.claude.model}`,
    "---",
    "",
    `<!-- Generated by \`node tools/sync-agent-proxies.mjs --write\` from ${agent.common}. Do not edit here. -->`,
    "",
    canonical,
  ].join("\n");
}

function codexMetadata(skill) {
  return `policy:\n  allow_implicit_invocation: ${yamlValue(skill.codex.allow_implicit_invocation)}\n`;
}

function expectedInventory(manifest) {
  const files = new Map();
  const directories = new Set();
  const roots = [];
  for (const [runtimeName, runtime] of Object.entries(manifest.runtimes)) {
    files.set(resolve(repoRoot, runtime.root_file), rootProxy(runtimeName, runtime));
    const skillRoot = resolve(repoRoot, runtime.skill_root);
    roots.push(skillRoot);
    directories.add(skillRoot);
    for (const skill of manifest.skills) {
      const skillDirectory = resolve(skillRoot, skill.name);
      directories.add(skillDirectory);
      files.set(
        resolve(skillDirectory, "SKILL.md"),
        skillProxy(runtimeName, runtime, skill),
      );
      if (runtimeName === "codex") {
        const agentsDirectory = resolve(skillDirectory, "agents");
        directories.add(agentsDirectory);
        files.set(
          resolve(agentsDirectory, "openai.yaml"),
          codexMetadata(skill),
        );
      }
    }
    if (runtime.agent_root !== undefined) {
      const agentRoot = resolve(repoRoot, runtime.agent_root);
      roots.push(agentRoot);
      directories.add(agentRoot);
      for (const agent of manifest.agents) {
        files.set(resolve(agentRoot, `${agent.name}.md`), agentProxy(agent));
      }
    }
  }
  return { directories, files, roots };
}

function pathType(path) {
  try {
    const stat = lstatSync(path);
    if (stat.isSymbolicLink()) return "symlink";
    if (stat.isDirectory()) return "directory";
    if (stat.isFile()) return "file";
    return "other";
  } catch (error) {
    if (error.code === "ENOENT") return "missing";
    throw error;
  }
}

function unsafeAncestors(path) {
  const parent = dirname(path);
  const fromRoot = relative(repoRoot, parent);
  if (!fromRoot) return [];
  if (
    fromRoot === ".."
    || fromRoot.startsWith(`..${sep}`)
    || resolve(repoRoot, fromRoot) !== parent
  ) {
    return [path];
  }
  let current = repoRoot;
  for (const segment of fromRoot.split(sep)) {
    current = resolve(current, segment);
    const type = pathType(current);
    if (type === "missing") return [];
    if (type !== "directory") return [current];
  }
  return [];
}

function collectActualPaths(path, paths, expectedPaths) {
  const type = pathType(path);
  if (type === "missing") return;
  paths.set(path, type);
  if (type !== "directory" || !expectedPaths.has(path)) return;
  for (const entry of readdirSync(path).sort()) {
    collectActualPaths(resolve(path, entry), paths, expectedPaths);
  }
}

function findUnexpected(roots, expectedPaths) {
  const actualPaths = new Map();
  for (const root of roots) collectActualPaths(root, actualPaths, expectedPaths);
  return [...actualPaths.keys()]
    .filter((path) => !expectedPaths.has(path))
    .sort();
}

function displayPaths(paths) {
  return paths.map((path) => relative(repoRoot, path));
}

function reportProblems({ drifted, invalid, missing, unexpected }) {
  const sections = [
    ["Missing generated proxies", missing],
    ["Drifted generated proxies", drifted],
    ["Invalid generated proxy path types", invalid],
    ["Unexpected generated proxy paths", unexpected],
  ].filter(([, paths]) => paths.length);
  console.error(
    sections
      .map(([label, paths]) => `${label}:\n- ${displayPaths(paths).join("\n- ")}`)
      .join("\n"),
  );
}

function main() {
  const [mode, ...extra] = process.argv.slice(2);
  if (!["--write", "--check"].includes(mode) || extra.length) {
    throw new Error("Usage: node tools/sync-agent-proxies.mjs (--write | --check)");
  }
  const { directories, files, roots } = expectedInventory(readManifest());
  const invalidAncestors = new Set();
  for (const path of [...directories, ...files.keys()]) {
    for (const ancestor of unsafeAncestors(path)) invalidAncestors.add(ancestor);
  }
  if (invalidAncestors.size) {
    reportProblems({
      drifted: [],
      invalid: [...invalidAncestors].sort(),
      missing: [],
      unexpected: [],
    });
    process.exitCode = 1;
    return;
  }

  const invalid = [];
  for (const path of directories) {
    const type = pathType(path);
    if (!["missing", "directory"].includes(type)) invalid.push(path);
  }
  for (const path of files.keys()) {
    const type = pathType(path);
    if (!["missing", "file"].includes(type)) invalid.push(path);
  }
  if (invalid.length) {
    reportProblems({ drifted: [], invalid, missing: [], unexpected: [] });
    process.exitCode = 1;
    return;
  }

  const missing = [];
  const drifted = [];
  for (const [path, expected] of files) {
    const type = pathType(path);
    if (type === "missing") missing.push(path);
    else if (type === "file" && readFileSync(path, "utf8") !== expected) drifted.push(path);
  }

  const expectedPaths = new Set([...directories, ...files.keys()]);
  if (mode === "--check") {
    const unexpected = findUnexpected(roots, expectedPaths);
    if (!missing.length && !drifted.length && !unexpected.length) {
      console.log(JSON.stringify({
        status: "current",
        files: files.size,
        changed: [],
        unexpected: [],
      }, null, 2));
      return;
    }
    reportProblems({ drifted, invalid: [], missing, unexpected });
    process.exitCode = 1;
    return;
  }

  const changed = [...missing, ...drifted];
  if (mode === "--write") {
    for (const path of changed) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, files.get(path), "utf8");
    }
  }
  const unexpected = findUnexpected(roots, expectedPaths);
  console.log(JSON.stringify({
    status: unexpected.length ? "written_with_orphans" : "written",
    files: files.size,
    changed: displayPaths(changed),
    unexpected: displayPaths(unexpected),
  }, null, 2));
  if (unexpected.length) {
    reportProblems({ drifted: [], invalid: [], missing: [], unexpected });
    process.exitCode = 1;
  }
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
